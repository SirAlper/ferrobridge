//! Builds ferrobridge bridges from the user's `build.rs`.
//!
//! There are two uses:
//!
//! - **Committed files (default).** The `bridge.rs` / `shim.h` / `shim.cc` generated with
//!   `ferrobridge generate` and put into the repository are compiled (ADR-0004). No libclang needed.
//! - **Build-time generation (the `generate` feature).** The header is read with libclang inside
//!   `build.rs`, and the bridge is generated under `$OUT_DIR/ferrobridge/<name>/` and compiled. The Rust
//!   side uses it with `ferrobridge::include_bridge!("<name>")`. This path is chosen when the generated
//!   files must not enter the repository (e.g. a C++ library with a different license; ADR-0008).
//!
//! ```no_run
//! // build.rs: the body of `fn main`
//! let mut build = ferrobridge_build::Build::new();
//! build
//!     .committed("src/generated/vehicle")
//!     .include_dir("src/generated")
//!     .include_dir("cpp/include")
//!     .file("cpp/vehicle.cc");
//! if let Err(error) = build.compile("vehicle") {
//!     panic!("{error}");
//! }
//! ```
//!
//! All bridges, the user's C++ sources and the shims are compiled into a single static library, with
//! the same include paths, defines and C++ standard. In `generate` mode the same settings are also
//! passed to the libclang that reads the header.

use std::path::{Path, PathBuf};

/// The default C++ standard (cxx needs C++11, ferrobridge's shims C++17).
const DEFAULT_STD: &str = "c++17";
/// The files that must be in a committed bridge directory.
const BRIDGE_FILES: [&str; 3] = ["bridge.rs", "shim.h", "shim.cc"];

/// An error that stops the build in `build.rs`. `Display` gives all the details (libclang diagnostics,
/// `ferrobridge.toml` lines) over several lines.
#[derive(Debug, thiserror::Error)]
pub enum Error {
    /// An expected file is missing from a committed bridge directory.
    #[error(
        "{} not found: the directory must contain the `bridge.rs`, `shim.h` and \
         `shim.cc` generated by `ferrobridge generate`",
        .0.display()
    )]
    MissingFile(PathBuf),
    /// An environment variable Cargo gives to `build.rs` is missing.
    #[error(
        "the `{0}` environment variable is missing; `compile` can only be called from `build.rs`"
    )]
    MissingEnv(&'static str),
    /// The bridge name cannot be used as a file and C++ namespace name.
    #[error(
        "invalid bridge name `{0}`: it must start with a letter or `_` and consist of letters, digits and `_`"
    )]
    InvalidName(String),
    /// A generated file could not be written.
    #[error("could not write {}: {message}", path.display())]
    Write {
        /// The file.
        path: PathBuf,
        /// The operating system's error message.
        message: String,
    },
    /// The header could not be read, the annotations are invalid, or code could not be generated.
    #[error("ferrobridge: {header}: {message}")]
    Generate {
        /// The header's path.
        header: String,
        /// What happened; may be several lines.
        message: String,
    },
}

/// Compiling one or more bridges and the user's C++ sources.
#[derive(Debug, Clone, Default)]
pub struct Build {
    committed: Vec<PathBuf>,
    #[cfg(feature = "generate")]
    generated: Vec<Generate>,
    include_dirs: Vec<PathBuf>,
    defines: Vec<(String, Option<String>)>,
    files: Vec<PathBuf>,
    std: Option<String>,
    flags: Vec<String>,
}

impl Build {
    /// An empty build.
    pub fn new() -> Self {
        Self::default()
    }

    /// The directory where the output of `ferrobridge generate` is committed (`bridge.rs`, `shim.h`,
    /// `shim.cc`). The roots from which the `--include-as` and `--shim-include` paths given during
    /// generation are resolved must be given separately with [`Build::include_dir`].
    pub fn committed(&mut self, dir: impl AsRef<Path>) -> &mut Self {
        self.committed.push(dir.as_ref().to_path_buf());
        self
    }

    /// A bridge to generate during the build (the `generate` feature).
    #[cfg(feature = "generate")]
    pub fn generate(&mut self, bridge: Generate) -> &mut Self {
        self.generated.push(bridge);
        self
    }

    /// A C++ include directory (`-I`). Also passed to libclang in `generate` mode.
    pub fn include_dir(&mut self, dir: impl AsRef<Path>) -> &mut Self {
        self.include_dirs.push(dir.as_ref().to_path_buf());
        self
    }

    /// A preprocessor definition (`-DNAME` or `-DNAME=value`). Also passed to libclang in `generate`
    /// mode.
    pub fn define(&mut self, name: &str, value: Option<&str>) -> &mut Self {
        self.defines
            .push((name.to_owned(), value.map(str::to_owned)));
        self
    }

    /// A user C++ source to compile (the implementation of the bound library).
    pub fn file(&mut self, path: impl AsRef<Path>) -> &mut Self {
        self.files.push(path.as_ref().to_path_buf());
        self
    }

    /// Several C++ sources.
    pub fn files<P: AsRef<Path>>(&mut self, paths: impl IntoIterator<Item = P>) -> &mut Self {
        for path in paths {
            self.file(path);
        }
        self
    }

    /// The C++ standard (default `c++17`). Also passed to libclang in `generate` mode.
    pub fn std(&mut self, std: &str) -> &mut Self {
        self.std = Some(std.to_owned());
        self
    }

    /// An extra argument passed only to the C++ compiler (not to libclang).
    pub fn flag(&mut self, flag: &str) -> &mut Self {
        self.flags.push(flag.to_owned());
        self
    }

    fn cpp_std(&self) -> &str {
        self.std.as_deref().unwrap_or(DEFAULT_STD)
    }

    /// Compiles the bridges (generating them first if needed) and the C++ sources into a static
    /// library named `lib_name`, and tells Cargo to link it.
    ///
    /// # Errors
    ///
    /// Returns an error if a committed file is missing, the header cannot be read in `generate` mode,
    /// `ferrobridge.toml` does not match the header, or the files cannot be written. C++ compile errors
    /// are printed by `cxx-build` and stop the build.
    pub fn compile(&self, lib_name: &str) -> Result<(), Error> {
        let mut bridges = Vec::new();
        let mut shims = Vec::new();
        #[cfg_attr(not(feature = "generate"), allow(unused_mut))]
        let mut include_dirs = self.include_dirs.clone();

        for dir in &self.committed {
            for file in BRIDGE_FILES {
                let path = dir.join(file);
                if !path.is_file() {
                    return Err(Error::MissingFile(path));
                }
                // `cxx-build` prints the line for `bridge.rs`.
                if file != "bridge.rs" {
                    rerun_if_changed(&path);
                }
            }
            bridges.push(dir.join("bridge.rs"));
            shims.push(dir.join("shim.cc"));
        }

        #[cfg(feature = "generate")]
        if !self.generated.is_empty() {
            let out_dir = std::env::var_os("OUT_DIR").ok_or(Error::MissingEnv("OUT_DIR"))?;
            let root = PathBuf::from(out_dir).join("ferrobridge");
            for bridge in &self.generated {
                let generated = generate::run(self, bridge, &root)?;
                bridges.push(generated.dir.join("bridge.rs"));
                shims.push(generated.dir.join("shim.cc"));
                include_dirs.extend(generated.include_dirs);
            }
            // `<name>/shim.h` is resolved from here.
            include_dirs.push(root);
        }

        for path in &self.files {
            rerun_if_changed(path);
        }
        for dir in &self.include_dirs {
            // Cargo scans directories itself: it rebuilds when an included header changes.
            rerun_if_changed(dir);
        }

        let mut build = cxx_build::bridges(&bridges);
        build.files(&shims).files(&self.files);
        for dir in &include_dirs {
            build.include(dir);
        }
        for (name, value) in &self.defines {
            build.define(name, value.as_deref());
        }
        build.std(self.cpp_std());
        for flag in &self.flags {
            build.flag(flag);
        }
        build.compile(lib_name);
        Ok(())
    }
}

fn rerun_if_changed(path: &Path) {
    println!("cargo:rerun-if-changed={}", path.display());
}

/// The bridge name: used as a file path part, a C++ namespace and a Rust macro argument.
#[cfg(feature = "generate")]
fn valid_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Writes if the content differs. Rewriting the same content would change the file time and cause
/// an unnecessary C++ build.
#[cfg(feature = "generate")]
fn write_if_changed(path: &Path, contents: &str) -> Result<(), Error> {
    use std::fs;
    if fs::read_to_string(path).is_ok_and(|old| old == contents) {
        return Ok(());
    }
    let error = |e: std::io::Error| Error::Write {
        path: path.to_path_buf(),
        message: e.to_string(),
    };
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(error)?;
    }
    fs::write(path, contents).map_err(error)
}

#[cfg(feature = "generate")]
pub use generate::Generate;

#[cfg(feature = "generate")]
mod generate {
    use std::path::{Path, PathBuf};

    use ferrobridge_analysis::{Annotations, BridgePlan};
    use ferrobridge_codegen::CodegenOptions;
    use ferrobridge_parser::{ParseOptions, ParserError};

    use crate::{Build, Error, rerun_if_changed, valid_name, write_if_changed};

    /// A bridge to generate inside `build.rs`: from which headers, with which name, with which
    /// annotations. A type defined in one header can be used in functions in the bridge's other
    /// headers.
    #[derive(Debug, Clone)]
    pub struct Generate {
        /// (header, the `#include` path in the shim; the file name if `None`)
        headers: Vec<(PathBuf, Option<String>)>,
        name: String,
        config: Option<PathBuf>,
        prelude: Vec<String>,
        clang_args: Vec<String>,
    }

    impl Generate {
        /// A bridge named `name`. The name is used for the output directory (`$OUT_DIR/ferrobridge/<name>/`),
        /// the shim namespace (`ferrobridge::<name>`) and `ferrobridge::include_bridge!("<name>")`.
        /// Headers are added with [`Generate::header`] / [`Generate::header_as`].
        pub fn new(name: &str) -> Self {
            Self {
                headers: Vec::new(),
                name: name.to_owned(),
                config: None,
                prelude: Vec::new(),
                clang_args: Vec::new(),
            }
        }

        /// Adds a header to the bridge. The shim includes it by its file name; the header's directory
        /// is added to the include paths.
        #[must_use]
        pub fn header(mut self, path: impl AsRef<Path>) -> Self {
            self.headers.push((path.as_ref().to_path_buf(), None));
            self
        }

        /// Adds a header to the bridge; the shim includes it by the path `include` (e.g. `"AP_Math/crc.h"`).
        /// The path must be resolvable from the [`Build::include_dir`] roots.
        #[must_use]
        pub fn header_as(mut self, path: impl AsRef<Path>, include: &str) -> Self {
            self.headers
                .push((path.as_ref().to_path_buf(), Some(include.to_owned())));
            self
        }

        /// Ownership annotations (`ferrobridge.toml`).
        #[must_use]
        pub fn config(mut self, path: impl AsRef<Path>) -> Self {
            self.config = Some(path.as_ref().to_path_buf());
            self
        }

        /// A file to include before the header (for headers that do not compile on their own;
        /// like `ferrobridge generate --prelude`). The shim also includes it before the header.
        #[must_use]
        pub fn prelude(mut self, include: &str) -> Self {
            self.prelude.push(include.to_owned());
            self
        }

        /// An extra argument passed only to libclang.
        #[must_use]
        pub fn clang_arg(mut self, arg: &str) -> Self {
            self.clang_args.push(arg.to_owned());
            self
        }
    }

    /// A generated bridge.
    pub(crate) struct Generated {
        /// The directory of `bridge.rs`, `shim.h`, `shim.cc`.
        pub(crate) dir: PathBuf,
        /// Include directories that must be added to the C++ build.
        pub(crate) include_dirs: Vec<PathBuf>,
    }

    pub(crate) fn run(build: &Build, bridge: &Generate, root: &Path) -> Result<Generated, Error> {
        if !valid_name(&bridge.name) {
            return Err(Error::InvalidName(bridge.name.clone()));
        }
        let header_text = bridge
            .headers
            .iter()
            .map(|(path, _)| path.display().to_string())
            .collect::<Vec<_>>()
            .join(", ");
        let fail = |message: String| Error::Generate {
            header: header_text.clone(),
            message,
        };
        if bridge.headers.is_empty() {
            return Err(fail(format!(
                "no header was added to the `{}` bridge (`Generate::header`)",
                bridge.name
            )));
        }
        let paths: Vec<&Path> = bridge.headers.iter().map(|(p, _)| p.as_path()).collect();
        for path in &paths {
            rerun_if_changed(path);
        }

        // Annotations first: `[templates]` goes to the parser as instantiations.
        let annotations = match &bridge.config {
            Some(path) => {
                rerun_if_changed(path);
                Annotations::from_file(path).map_err(|e| fail(e.to_string()))?
            }
            None => Annotations::default(),
        };
        let mut options = parse_options(build, bridge);
        options.instantiate = annotations.instantiations();
        let module = ferrobridge_parser::parse_headers(&paths, &options)
            .map_err(|error| fail(describe_parser_error(&error)))?;
        let plan = ferrobridge_analysis::check(&module, &annotations).map_err(|issues| {
            let lines: Vec<String> = issues.iter().map(|i| format!("  {i}")).collect();
            fail(format!(
                "`ferrobridge.toml` does not match the headers:\n{}",
                lines.join("\n")
            ))
        })?;

        let mut include_dirs = Vec::new();
        let mut header_includes = Vec::with_capacity(bridge.headers.len());
        for (path, include) in &bridge.headers {
            header_includes.push(match include {
                Some(include) => include.clone(),
                None => {
                    if let Some(parent) = path.parent() {
                        include_dirs.push(parent.to_path_buf());
                    }
                    path.file_name().map_or_else(
                        || path.display().to_string(),
                        |n| n.to_string_lossy().into_owned(),
                    )
                }
            });
        }
        let options = CodegenOptions {
            header_includes,
            shim_include: format!("{}/shim.h", bridge.name),
            shim_namespace: format!("ferrobridge::{}", bridge.name),
            prelude: bridge.prelude.clone(),
        };
        let files =
            ferrobridge_codegen::generate(&plan, &options).map_err(|e| fail(e.to_string()))?;

        let dir = root.join(&bridge.name);
        write_if_changed(&dir.join("bridge.rs"), &files.bridge_rs)?;
        write_if_changed(&dir.join("shim.h"), &files.shim_h)?;
        write_if_changed(&dir.join("shim.cc"), &files.shim_cc)?;

        for warning in &plan.annotation_warnings {
            println!("cargo:warning=ferrobridge: {warning}");
        }
        let label = match bridge.headers.as_slice() {
            [(path, _)] => path.display().to_string(),
            many => format!("`{}` ({} headers)", bridge.name, many.len()),
        };
        summary(&plan, &label, &dir.join("bridge.rs"));
        Ok(Generated { dir, include_dirs })
    }

    /// The settings passed to libclang: the build's include directories, defines and standard.
    pub(crate) fn parse_options(build: &Build, bridge: &Generate) -> ParseOptions {
        let mut extra_args = Vec::new();
        for dir in &build.include_dirs {
            extra_args.push(format!("-I{}", dir.display()));
        }
        for (name, value) in &build.defines {
            extra_args.push(match value {
                Some(value) => format!("-D{name}={value}"),
                None => format!("-D{name}"),
            });
        }
        extra_args.extend(bridge.clang_args.iter().cloned());
        ParseOptions {
            std: build.cpp_std().to_owned(),
            extra_args,
            prelude: bridge.prelude.clone(),
            instantiate: Vec::new(),
        }
    }

    fn describe_parser_error(error: &ParserError) -> String {
        match error {
            ParserError::ParseFailed { diagnostics } => {
                let lines: Vec<String> = diagnostics.iter().map(|d| format!("  {d}")).collect();
                format!("{error}\n{}", lines.join("\n"))
            }
            ParserError::LoadFailed(_) => format!(
                "{error}\n  `LIBCLANG_PATH` must point to the directory containing libclang (macOS: \
                 `$(brew --prefix llvm)/lib`)."
            ),
            other => other.to_string(),
        }
    }

    /// A single summary warning if there are unbound items: printing them one by one would be hundreds
    /// of lines for large libraries; the list is at the top of the generated file.
    fn summary(plan: &BridgePlan, header: &str, bridge_rs: &Path) {
        if plan.skipped.is_empty() && plan.suggestions.is_empty() {
            return;
        }
        let mut message = format!(
            "cargo:warning=ferrobridge: {header}: {} items not bound (list: {})",
            plan.skipped.len(),
            bridge_rs.display()
        );
        if !plan.suggestions.is_empty() {
            message.push_str(&format!(
                "; {} places need an annotation (`ferrobridge suggest`)",
                plan.suggestions.len()
            ));
        }
        println!("{message}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[cfg(feature = "generate")]
    #[test]
    fn bridge_names_must_be_identifiers() {
        assert!(valid_name("ap_math"));
        assert!(valid_name("_x2"));
        assert!(!valid_name(""));
        assert!(!valid_name("2x"));
        assert!(!valid_name("ap-math"));
        assert!(!valid_name("a/b"));
    }

    #[cfg(feature = "generate")]
    #[test]
    fn unchanged_files_are_not_rewritten() {
        use std::fs;
        let dir = std::env::temp_dir().join(format!("ferrobridge-build-{}", std::process::id()));
        let path = dir.join("x/bridge.rs");
        write_if_changed(&path, "a").unwrap();
        let first = fs::metadata(&path).unwrap().modified().unwrap();
        std::thread::sleep(std::time::Duration::from_millis(20));
        write_if_changed(&path, "a").unwrap();
        assert_eq!(fs::metadata(&path).unwrap().modified().unwrap(), first);
        write_if_changed(&path, "b").unwrap();
        assert_eq!(fs::read_to_string(&path).unwrap(), "b");
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn missing_committed_file_is_reported_before_compiling() {
        let error = Build::new()
            .committed("/missing/bridge/dir")
            .compile("x")
            .unwrap_err();
        assert!(matches!(&error, Error::MissingFile(p) if p.ends_with("bridge.rs")));
        assert!(error.to_string().contains("ferrobridge generate"));
    }

    #[cfg(feature = "generate")]
    #[test]
    fn libclang_sees_the_same_include_dirs_defines_and_std() {
        let mut build = Build::new();
        build
            .include_dir("libraries")
            .define("CONFIG_HAL_BOARD", Some("HAL_BOARD_SITL"))
            .define("NDEBUG", None)
            .std("c++20")
            .flag("-w");
        let bridge = Generate::new("crc")
            .header_as("libraries/AP_Math/crc.h", "AP_Math/crc.h")
            .prelude("AP_Math/AP_Math.h")
            .clang_arg("-Wno-everything");
        let options = generate::parse_options(&build, &bridge);
        assert_eq!(options.std, "c++20");
        assert_eq!(
            options.extra_args,
            [
                "-Ilibraries",
                "-DCONFIG_HAL_BOARD=HAL_BOARD_SITL",
                "-DNDEBUG",
                "-Wno-everything"
            ]
        );
        assert_eq!(options.prelude, ["AP_Math/AP_Math.h"]);
    }
}
