//! `ferrobridge` komut satırı aracı.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use clap::{Parser, Subcommand};
use ferrobridge_analysis::{Annotations, BridgePlan};
use ferrobridge_codegen::{CodegenOptions, GeneratedFiles};
use ferrobridge_parser::{ParseOptions, ParserError};

/// C++ header'larından güvenli Rust binding'leri üretir.
#[derive(Parser)]
#[command(name = "ferrobridge", version, about)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Geliştirme ortamını kontrol eder (libclang erişimi).
    Doctor,
    /// Bir C++ header'ını okur ve içinde bulduklarını (IR) JSON olarak basar.
    Parse {
        /// Okunacak C++ header dosyası.
        header: PathBuf,
        #[command(flatten)]
        parse: ParseArgs,
    },
    /// Bir C++ header'ından cxx bridge'i (`bridge.rs`) ve C++ shim'ini (`shim.h`, `shim.cc`)
    /// üretir. Bağlanamayan her öğe nedeniyle birlikte uyarı olarak basılır.
    Generate {
        /// Okunacak C++ header dosyası.
        header: PathBuf,
        /// Üç dosyanın yazılacağı dizin (yoksa oluşturulur).
        #[arg(long)]
        out_dir: PathBuf,
        /// Shim'in header'ı `#include` ederken kullanacağı yol. Varsayılan: header'ın dosya adı.
        #[arg(long)]
        include_as: Option<String>,
        /// Bridge'in `shim.h`'yi `#include` ederken kullanacağı yol.
        #[arg(long, default_value = "shim.h")]
        shim_include: String,
        /// Shim fonksiyonlarının C++ namespace'i. Varsayılan: `ferrobridge::<header adı>`.
        #[arg(long)]
        shim_namespace: Option<String>,
        /// Sahiplik açıklamaları dosyası (`ferrobridge.toml`). Verilmezse açıklama yok sayılır
        /// ve sahipliği belirsiz pointer'lar bağlanmaz.
        #[arg(long)]
        config: Option<PathBuf>,
        /// ferrobridge'in üretmediği (elle yazılmış görünen) dosyaların da üzerine yaz.
        #[arg(long)]
        force: bool,
        #[command(flatten)]
        parse: ParseArgs,
    },
    /// Açıklama gerektiren her pointer/referans için yorum satırlı bir `ferrobridge.toml`
    /// taslağı basar. Emin olduğun satırları açıp `generate --config` ile kullan.
    Suggest {
        /// Okunacak C++ header dosyası.
        header: PathBuf,
        /// Var olan açıklamalar; bunların çözdüğü yerler taslağa girmez.
        #[arg(long)]
        config: Option<PathBuf>,
        #[command(flatten)]
        parse: ParseArgs,
    },
}

/// Header'ı okuma ayarları; `parse`, `generate` ve `suggest` için ortak.
#[derive(clap::Args)]
struct ParseArgs {
    /// C++ standardı (clang'a `-std=<değer>` olarak geçer).
    #[arg(long, default_value = "c++17")]
    std: String,
    /// Header'dan önce include edilecek dosya; kendi başına derlenmeyen header'lar için.
    /// Tekrarlanabilir, verildiği sırayla include edilir; buradaki bildirimler bağlanmaz.
    /// `generate`'te shim de header'dan önce bunu include eder: include yollarından çözülen bir
    /// ad verin (ör. `AP_Math/AP_Math.h`).
    #[arg(long, value_name = "HEADER")]
    prelude: Vec<String>,
    /// `--` sonrasında clang'a olduğu gibi geçirilecek argümanlar (ör. `-- -I include`).
    #[arg(last = true)]
    clang_args: Vec<String>,
}

impl From<ParseArgs> for ParseOptions {
    fn from(args: ParseArgs) -> Self {
        ParseOptions {
            std: args.std,
            extra_args: args.clang_args,
            prelude: args.prelude,
        }
    }
}

/// Üretilen her dosyanın ilk satırı; üzerine yazmadan önce bununla kontrol edilir.
const GENERATED_MARKER: &str = "// @generated by ferrobridge";
const OUTPUT_FILES: [&str; 3] = ["bridge.rs", "shim.h", "shim.cc"];

const LIBCLANG_HINT: &str =
    "  İpucu: `brew install llvm` ve ardından `export LIBCLANG_PATH=\"$(brew --prefix llvm)/lib\"`";

fn main() -> ExitCode {
    let cli = Cli::parse();
    match cli.command {
        Command::Doctor => doctor(),
        Command::Parse {
            header,
            parse: args,
        } => parse(&header, &args.into()),
        Command::Generate {
            header,
            out_dir,
            include_as,
            shim_include,
            shim_namespace,
            config,
            force,
            parse: args,
        } => {
            if !force {
                let foreign = foreign_files(&out_dir);
                if !foreign.is_empty() {
                    eprintln!(
                        "✗ şu dosyalar ferrobridge tarafından üretilmemiş görünüyor, üzerine \
                         yazılmadı: {}",
                        foreign.join(", ")
                    );
                    eprintln!("  Yine de yazmak için `--force` kullanın.");
                    return ExitCode::FAILURE;
                }
            }
            let options = CodegenOptions {
                header_include: include_as.unwrap_or_else(|| file_name(&header)),
                shim_include,
                shim_namespace: shim_namespace
                    .unwrap_or_else(|| format!("ferrobridge::{}", identifier_from(&header))),
                prelude: args.prelude.clone(),
            };
            generate(&header, &out_dir, &options, config.as_deref(), args.into())
        }
        Command::Suggest {
            header,
            config,
            parse: args,
        } => suggest(&header, config.as_deref(), args.into()),
    }
}

/// Header'ı okur, açıklamaları yükler ve analizi çalıştırır. Hata olursa basıp çıkış kodunu
/// döndürür. Gereksiz açıklama uyarıları burada basılır.
fn analyze(
    header: &Path,
    config: Option<&Path>,
    options: &ParseOptions,
) -> Result<BridgePlan, ExitCode> {
    let module = ferrobridge_parser::parse_header(header, options).map_err(|e| report(&e))?;
    let annotations = match config {
        Some(path) => Annotations::from_file(path).map_err(|error| {
            eprintln!("✗ {error}");
            ExitCode::FAILURE
        })?,
        None => Annotations::default(),
    };
    let plan = ferrobridge_analysis::check(&module, &annotations).map_err(|issues| {
        eprintln!("✗ açıklama dosyası header'la uyuşmuyor:");
        for issue in &issues {
            eprintln!("  ✗ {issue}");
        }
        ExitCode::FAILURE
    })?;
    for warning in &plan.annotation_warnings {
        eprintln!("⚠ {warning}");
    }
    Ok(plan)
}

fn suggest(header: &Path, config: Option<&Path>, options: ParseOptions) -> ExitCode {
    let plan = match analyze(header, config, &options) {
        Ok(plan) => plan,
        Err(code) => return code,
    };
    print!("{}", ferrobridge_analysis::render_suggestions(&plan));
    if !plan.suggestions.is_empty() {
        eprintln!(
            "ℹ {} yer açıklama bekliyor. Emin olduğun satırları açıp `generate --config` ile \
             kullan.",
            plan.suggestions.len()
        );
    }
    ExitCode::SUCCESS
}

fn generate(
    header: &Path,
    out_dir: &Path,
    options: &CodegenOptions,
    config: Option<&Path>,
    parse_options: ParseOptions,
) -> ExitCode {
    let plan = match analyze(header, config, &parse_options) {
        Ok(plan) => plan,
        Err(code) => return code,
    };
    let files = match ferrobridge_codegen::generate(&plan, options) {
        Ok(files) => files,
        Err(error) => {
            eprintln!("✗ {error}");
            return ExitCode::FAILURE;
        }
    };

    for skipped in &plan.skipped {
        eprintln!(
            "⚠ {} ({}:{}): {}",
            skipped.name, skipped.location.file, skipped.location.line, skipped.reason
        );
    }
    for note in &plan.notes {
        eprintln!(
            "ℹ {} ({}:{}): {}",
            note.name, note.location.file, note.location.line, note.reason
        );
    }

    if let Err(error) = write_files(out_dir, &files) {
        eprintln!("✗ dosyalar yazılamadı ({}): {error}", out_dir.display());
        return ExitCode::FAILURE;
    }
    let bound = plan.functions.len()
        + plan
            .classes
            .iter()
            .map(|c| c.constructors.len() + c.methods.len())
            .sum::<usize>();
    println!(
        "✓ {} sınıf, {} enum, {} sabit ve {bound} fonksiyon/metot bağlandı; {} öğe atlandı.",
        plan.classes.len(),
        plan.enums.len(),
        plan.constants.len(),
        plan.skipped.len()
    );
    if !plan.assumptions.is_empty() {
        println!(
            "  {} açıklamaya dayanan varsayım (üretilen dosyaların başında listelendi).",
            plan.assumptions.len()
        );
    }
    if !plan.suggestions.is_empty() {
        println!(
            "  {} yer açıklama bekliyor: `ferrobridge suggest {}`",
            plan.suggestions.len(),
            header.display()
        );
    }
    println!("  {}", out_dir.join("bridge.rs").display());
    println!("  {}", out_dir.join("shim.h").display());
    println!("  {}", out_dir.join("shim.cc").display());
    ExitCode::SUCCESS
}

/// `out_dir`'de var olan ama `@generated by ferrobridge` ile başlamayan çıktı dosyaları.
fn foreign_files(out_dir: &Path) -> Vec<String> {
    OUTPUT_FILES
        .iter()
        .map(|name| out_dir.join(name))
        .filter(|path| path.exists())
        .filter(|path| {
            fs::read_to_string(path)
                .map(|content| !content.starts_with(GENERATED_MARKER))
                .unwrap_or(true)
        })
        .map(|path| path.display().to_string())
        .collect()
}

fn write_files(out_dir: &Path, files: &GeneratedFiles) -> std::io::Result<()> {
    fs::create_dir_all(out_dir)?;
    fs::write(out_dir.join("bridge.rs"), &files.bridge_rs)?;
    fs::write(out_dir.join("shim.h"), &files.shim_h)?;
    fs::write(out_dir.join("shim.cc"), &files.shim_cc)
}

fn file_name(path: &Path) -> String {
    path.file_name().map_or_else(
        || path.display().to_string(),
        |name| name.to_string_lossy().into_owned(),
    )
}

/// Header adından geçerli bir C++ tanımlayıcısı (`my-lib.h` → `my_lib`).
fn identifier_from(path: &Path) -> String {
    let stem = path
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default();
    let mut ident: String = stem
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    if ident.is_empty() || ident.starts_with(|c: char| c.is_ascii_digit()) {
        ident.insert(0, '_');
    }
    ident
}

fn doctor() -> ExitCode {
    match ferrobridge_parser::libclang_version() {
        Ok(version) => {
            println!("✓ libclang bulundu: {version}");
            ExitCode::SUCCESS
        }
        Err(error) => report(&error),
    }
}

fn parse(header: &Path, options: &ParseOptions) -> ExitCode {
    let module = match ferrobridge_parser::parse_header(header, options) {
        Ok(module) => module,
        Err(error) => return report(&error),
    };
    match serde_json::to_string_pretty(&module) {
        Ok(json) => {
            println!("{json}");
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("✗ IR JSON'a çevrilemedi: {error}");
            ExitCode::FAILURE
        }
    }
}

/// Hatayı stderr'e basar: önce özet, sonra varsa her tanı ve ipucu.
fn report(error: &ParserError) -> ExitCode {
    eprintln!("✗ {error}");
    match error {
        ParserError::ParseFailed { diagnostics } => {
            for diagnostic in diagnostics {
                eprintln!("  ✗ {diagnostic}");
            }
        }
        ParserError::LoadFailed(_) => eprintln!("{LIBCLANG_HINT}"),
        _ => {}
    }
    ExitCode::FAILURE
}
